SUMMARY_ANCHOR = "实体划分遵循两条标准"
SUMMARY = (
    "把 10 个实体放在一起看，可以归为三类。用户域两个：用户与会话，负责身份与登录态；资源域三个：自习室、开放时段与座位，"
    "构成可预约的空间；业务域五个：预约、签到、状态日志、违约记录与反馈工单，记录一次预约从创建到结束的全过程。"
    "三类实体在字段设计上遵守同一组约定：时间统一用 `DATETIME` 并按 UTC 存储；状态一律用 `ENUM` 限定取值；"
    "凡是可能被后续变更影响的历史信息，都在业务表中保留快照字段；凡是能由数据库唯一索引表达的约束，都下沉到存储层，"
    "而不是只写在服务层。"
)


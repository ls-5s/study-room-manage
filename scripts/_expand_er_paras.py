out, added = [], 0
for line in lines:
    out.append(line)
    s = line.strip()
    for anchor, text in ADD.items():
        if s.startswith(anchor):
            out.append("")
            out.append(text)
            added += 1
            break
    if s.startswith(SUMMARY_ANCHOR):
        out.append("")
        out.append(SUMMARY)
        added += 1

io.open(PATH, "w", encoding="utf-8").write("\n".join(out))
print("paragraphs inserted:", added)
